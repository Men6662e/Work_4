//OОП - это парадигма програмирования, в которой программа представляется как совокупность взаймодействуйщих объектов.
//Каждый объект является эксемпляром определённого класса и инкапсулирует в себе как дынные (поля), так и процедуры для их обработки (методы)

// ООП состоит из 3 китах!!

// Инкапсуляция: Объеденение данных и методов для их обработки в одном коипоненте (объекте) и сокрытие деталей и реализации от внешнего мира.
// Объект это чёрный ящик, который пердоставляет наружу только удобный интерфейс!

// Наследование: Механизм, который позволяет создавать новый класс на основе существующего, перенимая его свойства и поведение и добавляя свои.
// (Например, классы "Грузовик" и "Легковой автомобиль" могут исследовать общие свойства от класса "Автомобиля")!!!

// Полиморфизм: Способность объектов с одинаковым интерфейсом (например, с методом Move()) иметь различную реализацию этого интерфейса.
// (Например, Move() для объекта "Рыба" будет означать "плыть", а для объекта "птица" - "летать".

// Класс - это пользовательский тип данных, который служит шаблоном или чертежом для создания объектов.
// Класс определяет, какие данные (поля) и какое поведение (методы) будут у всех объектов, созданных на его основе!
// По сути, объявляя класс, мы создаём новый тип данных в нашей программе, наравне со встроенными int, string и double